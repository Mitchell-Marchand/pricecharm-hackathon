export const TRADES_BY_ID = Object.fromEntries(TRADES.map((trade) => [trade.id, trade]));

/** The trade's name, the owner's own words for it, or a fallback. */
export function tradeName(tradeId, customTrade) {
  if (tradeId && TRADES_BY_ID[tradeId]) return TRADES_BY_ID[tradeId].name;
  return (customTrade || '').trim() || 'Your trade';
}
