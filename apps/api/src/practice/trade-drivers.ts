/**
 * What each trade's price usually depends on, for the Charm to ask an owner about during
 * practice, one question per customer. Each trade's list starts with what moves a price the most,
 * so the first few questions are the ones most worth asking.
 */
export type TradeDriver = {
  /** Unique within the trade, kebab-case: 'tree-height'. */
  key: string;
  /** A short name; the saved note starts with it: "Tree height: About 25% more over 30 ft." */
  label: string;
  /** The question to the owner, plain and short (90 characters at most). */
  ask: string;
  /**
   * Two or three tap answers in the owner's own voice, each one a way it's commonly priced, with
   * a rough amount where one fits. Percentages or relative words only, never a currency amount.
   */
  answers: string[];
  /** The tap answer that means it doesn't change their price, or they don't do it. */
  no: string;
  /**
   * What the live chat asks a customer when it matters, 90 characters at most. Left out when a
   * customer couldn't answer it.
   */
  customer?: string;
  /** Only when it's about some of the trade's services, named exactly as in packages/trades. */
  services?: string[];
};

